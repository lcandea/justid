// @ts-check
// Dev-only: writes app/js/core/qr-codes.js, the QR codes printed on the PDF, with the `qrcode` package
// (a dev dependency: it is never shipped, the site only gets the generated constants).
// The URLs are fixed and carry no language: /why and the landing open in the reader's own language.
// Re-run after changing a URL: npm run make-qr (tests/unit/qr.test.mjs fails if the file is stale).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import QRCode from 'qrcode';

/** The codes: why = for the recipient, why this copy is enough; use = try JustID. */
export const QR_URLS = {
  why: 'https://justid.candea.es/why#receive',
  use: 'https://justid.candea.es/',
};

/** The generated module source. */
export function qrModuleSource() {
  const entries = Object.entries(QR_URLS).map(([key, url]) => {
    const { size, data } = QRCode.create(url, { errorCorrectionLevel: 'M' }).modules; // data: row-major, 1 = dark
    const rows = Array.from({ length: size }, (_, y) => `      '${Array.from(data.subarray(y * size, (y + 1) * size)).join('')}',`).join('\n');
    return `  ${key}: {\n    url: '${url}',\n    size: ${size},\n    rows: [\n${rows}\n    ],\n  },`;
  });
  return `// @ts-check
// GENERATED by tools/make-qr.mjs (npm run make-qr). Do not edit by hand.
// The QR codes printed on the PDF, as rows of modules ('1' = dark), without the quiet zone.
// Fixed URLs only: nothing about the user or the document is ever encoded.

/** @typedef {{ url: string, size: number, rows: string[] }} QrCode */

/** @type {{ why: QrCode, use: QrCode }} */
export const QR_CODES = {
${entries.join('\n')}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'app/js/core/qr-codes.js');
  writeFileSync(out, qrModuleSource());
  console.log('Wrote', out);
}
